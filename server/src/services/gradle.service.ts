import fsSync from 'node:fs';
import path from 'node:path';
import type { Response } from 'express';
import * as archiverModule from 'archiver';
import { sessionService } from './session.service.js';
import { packageService } from './package.service.js';
import { ApiError } from '../utils/apiError.js';

const archiver: any = (archiverModule as any).default || archiverModule;

export class GradleService {
  /**
   * Generates a complete Android Studio Gradle Project ZIP stream and pipes it to the HTTP response
   */
  public async streamGradleProjectZip(sessionId: string, res: Response): Promise<void> {
    const session = await sessionService.getSession(sessionId);
    if (!session) {
      throw ApiError.notFound('Session not found', 'SESSION_NOT_FOUND');
    }

    const sessionDir = sessionService.getSessionDir(sessionId);
    const pkgInfo = await packageService.getPackageInfo(sessionId);

    const projectName = session.originalFilename
      ? session.originalFilename.replace(/\.apk$/i, '').replace(/[^a-zA-Z0-9_-]/g, '-')
      : 'DecompiledAndroidApp';

    const zipFilename = `${projectName}-android-studio-gradle.zip`;

    res.setHeader('Content-Type', 'application/zip');
    res.setHeader('Content-Disposition', `attachment; filename="${zipFilename}"`);
    res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate, private');

    const archive = archiver('zip', {
      zlib: { level: 6 },
    });

    archive.on('error', (err: any) => {
      console.error('Gradle ZIP archive error:', err);
      if (!res.headersSent) {
        res.status(500).json({ success: false, error: { message: err.message } });
      }
    });

    archive.pipe(res);

    // 1. Root settings.gradle
    const settingsGradle = `pluginManagement {
    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}
dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        mavenCentral()
    }
}

rootProject.name = "${projectName}"
include ':app'
`;
    archive.append(settingsGradle, { name: `${projectName}/settings.gradle` });

    // 2. Root build.gradle
    const rootBuildGradle = `// Top-level build file where you can add configuration options common to all sub-projects/modules.
plugins {
    id 'com.android.application' version '8.2.2' apply false
    id 'org.jetbrains.kotlin.android' version '1.9.22' apply false
}
`;
    archive.append(rootBuildGradle, { name: `${projectName}/build.gradle` });

    // 3. gradle.properties
    const gradleProperties = `org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8
android.useAndroidX=true
android.nonTransitiveRClass=false
kotlin.code.style=official
`;
    archive.append(gradleProperties, { name: `${projectName}/gradle.properties` });

    // 4. gradle/wrapper/gradle-wrapper.properties
    const wrapperProps = `distributionBase=GRADLE_USER_HOME
distributionPath=wrapper/dists
distributionUrl=https\\://services.gradle.org/distributions/gradle-8.4-bin.zip
networkTimeout=10000
validateDistributionUrl=true
zipStoreBase=GRADLE_USER_HOME
zipStorePath=wrapper/dists
`;
    archive.append(wrapperProps, {
      name: `${projectName}/gradle/wrapper/gradle-wrapper.properties`,
    });

    // 5. app/build.gradle
    const appBuildGradle = `plugins {
    id 'com.android.application'
}

android {
    namespace '${pkgInfo.packageName}'
    compileSdk 34

    defaultConfig {
        applicationId "${pkgInfo.packageName}"
        minSdk 24
        targetSdk 34
        versionCode ${Number(pkgInfo.versionCode) || 1}
        versionName "${pkgInfo.versionName || '1.0'}"

        testInstrumentationRunner "androidx.test.runner.AndroidJUnitRunner"
    }

    buildTypes {
        release {
            minifyEnabled false
            proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'
        }
    }
    compileOptions {
        sourceCompatibility JavaVersion.VERSION_17
        targetCompatibility JavaVersion.VERSION_17
    }
    lint {
        abortOnError false
        checkReleaseBuilds false
    }
}

dependencies {
    implementation 'androidx.appcompat:appcompat:1.6.1'
    implementation 'com.google.android.material:material:1.11.0'
    implementation 'androidx.constraintlayout:constraintlayout:2.1.4'
}
`;
    archive.append(appBuildGradle, { name: `${projectName}/app/build.gradle` });

    // 6. app/proguard-rules.pro
    archive.append('# Add project specific ProGuard rules here.\n', {
      name: `${projectName}/app/proguard-rules.pro`,
    });

    // 7. README.md explaining how to open in Android Studio
    const readmeMd = `# ${projectName} - Android Studio Gradle Project

Generated by **APK Studio (Reverse Engineering & Security Workspace)**.

- **Package Name:** \`${pkgInfo.packageName}\`
- **Version:** \`${pkgInfo.versionName || '1.0'} (${pkgInfo.versionCode || '1'})\`

## How to Open in Android Studio
1. Extract this ZIP archive.
2. Open **Android Studio** -> **Open** -> Select the \`${projectName}\` folder.
3. Let Gradle sync complete.
4. Decompiled Java classes are located under \`app/src/main/java/\`.
5. Decoded XML layouts, drawables, and manifest are under \`app/src/main/res/\` and \`app/src/main/AndroidManifest.xml\`.
6. Original Smali bytecode is preserved under \`smali-reference/\` for reference.
`;
    archive.append(readmeMd, { name: `${projectName}/README.md` });

    // 8. Copy AndroidManifest.xml -> app/src/main/AndroidManifest.xml
    const manifestPath = path.join(sessionDir, 'decoded', 'AndroidManifest.xml');
    if (fsSync.existsSync(manifestPath)) {
      archive.file(manifestPath, {
        name: `${projectName}/app/src/main/AndroidManifest.xml`,
      });
    }

    // 9. Copy decoded/res -> app/src/main/res
    const resDir = path.join(sessionDir, 'decoded', 'res');
    if (fsSync.existsSync(resDir)) {
      archive.directory(resDir, `${projectName}/app/src/main/res`);
    }

    // 10. Copy decoded/assets -> app/src/main/assets
    const assetsDir = path.join(sessionDir, 'decoded', 'assets');
    if (fsSync.existsSync(assetsDir)) {
      archive.directory(assetsDir, `${projectName}/app/src/main/assets`);
    }

    // 11. Copy decoded/lib -> app/src/main/jniLibs (Native .so libraries)
    const libDir = path.join(sessionDir, 'decoded', 'lib');
    if (fsSync.existsSync(libDir)) {
      archive.directory(libDir, `${projectName}/app/src/main/jniLibs`);
    }

    // 12. Copy Java sources from JADX -> app/src/main/java
    const javaSourcesSubdir = path.join(sessionDir, 'java', 'sources');
    const javaRootDir = path.join(sessionDir, 'java');
    if (fsSync.existsSync(javaSourcesSubdir)) {
      archive.directory(javaSourcesSubdir, `${projectName}/app/src/main/java`);
    } else if (fsSync.existsSync(javaRootDir)) {
      archive.directory(javaRootDir, `${projectName}/app/src/main/java`);
    }

    // 13. Include Smali reference directory
    const smaliDir = path.join(sessionDir, 'decoded', 'smali');
    if (fsSync.existsSync(smaliDir)) {
      archive.directory(smaliDir, `${projectName}/smali-reference`);
    }

    // 14. Include AI Recovered & Reconstructed Sources if any
    const recoveredDir = path.join(sessionDir, 'recovered');
    if (fsSync.existsSync(recoveredDir)) {
      archive.directory(recoveredDir, `${projectName}/ai-recovered-sources`);
    }

    await archive.finalize();
  }
}

export const gradleService = new GradleService();
